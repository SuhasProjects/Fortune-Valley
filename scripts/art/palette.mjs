// Generates src/styles/palette.css from art-src/palette.json. Owner: Agent 1.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));

/** Load and validate the palette: unique one-character keys and names, #rrggbb hex (null only for transparent). */
export function loadPalette() {
  const { colors } = JSON.parse(readFileSync(`${root}art-src/palette.json`, 'utf8'));
  const keys = new Set();
  const names = new Set();
  for (const c of colors) {
    if (typeof c.key !== 'string' || c.key.length !== 1) throw new Error(`Palette key must be one character: ${JSON.stringify(c)}`);
    if (keys.has(c.key)) throw new Error(`Duplicate palette key ${c.key}`);
    if (names.has(c.name)) throw new Error(`Duplicate palette name ${c.name}`);
    if (c.hex === null ? c.key !== '.' : !/^#[0-9a-f]{6}$/.test(c.hex)) throw new Error(`Bad hex for ${c.name}: ${c.hex}`);
    keys.add(c.key);
    names.add(c.name);
  }
  return colors;
}

export function writePaletteCss(colors = loadPalette()) {
  const lines = colors.filter((c) => c.hex).map((c) => `  --c-${c.name}: ${c.hex};`);
  const css = `/* GENERATED by scripts/art/palette.mjs from art-src/palette.json. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`;
  writeFileSync(`${root}src/styles/palette.css`, css);
  return css;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writePaletteCss();
  console.log('wrote src/styles/palette.css');
}
