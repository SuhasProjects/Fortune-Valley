// npm run art: compile every art-src/**/*.txt grid to public/art/**.png (+ .json) and regenerate the sprite
// manifest at src/game/art/manifest.ts. Output is deterministic; compiled files are committed. Owner: Agent 1.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expandFrames, paletteMap, parseGrid, pngBytes, renderSheet } from './grid.mjs';
import { loadPalette, writePaletteCss } from './palette.mjs';
import { writeGround } from './ground.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const srcDir = join(root, 'art-src');
const outDir = join(root, 'public/art');

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : name.endsWith('.txt') ? [p] : [];
  });
}

export function compileAll() {
  const colors = loadPalette();
  writePaletteCss(colors);
  const palette = paletteMap(colors);
  const manifest = {};
  const errors = [];
  for (const file of walk(srcDir)) {
    const rel = relative(srcDir, file).replace(/\\/g, '/').replace(/\.txt$/, '');
    try {
      const parsed = parseGrid(readFileSync(file, 'utf8'), palette, `art-src/${rel}.txt`);
      if (parsed.meta.kind !== 'sprite') continue; // masks and other data grids are consumed by their own scripts
      const frames = expandFrames(parsed, `art-src/${rel}.txt`);
      const target = join(outDir, `${rel}.png`);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, pngBytes(renderSheet(frames, palette)));
      if (parsed.meta.export2x) writeFileSync(join(outDir, `${rel}@2x.png`), pngBytes(renderSheet(frames, palette, 2)));
      const entry = {
        src: `/art/${rel}.png`,
        w: parsed.meta.w,
        h: parsed.meta.h,
        frames: frames.map((f) => f.name),
        ...(parsed.meta.anchor ? { anchor: parsed.meta.anchor } : {}),
        ...(parsed.meta.slice ? { slice: parsed.meta.slice } : {}),
        ...(parsed.meta.speed ? { speed: parsed.meta.speed } : {}),
      };
      writeFileSync(join(outDir, `${rel}.json`), `${JSON.stringify(entry, null, 2)}\n`);
      manifest[rel] = entry;
    } catch (e) {
      errors.push(e.message);
    }
  }
  if (errors.length) throw new Error(`Art compile failed:\n${errors.join('\n')}`);
  Object.assign(manifest, writeGround(root));
  const ts = `// GENERATED by scripts/art/compile.mjs (npm run art). Do not edit by hand.\n`
    + `export interface SpriteMeta { src: string; w: number; h: number; frames: readonly string[]; anchor?: readonly [number, number]; slice?: number; speed?: number }\n`
    + `const sprites = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, SpriteMeta>\n`
    + `export type SpriteName = keyof typeof sprites\n`
    + `export const SPRITES: Readonly<Record<SpriteName, SpriteMeta>> = sprites\n`;
  writeFileSync(join(root, 'src/game/art/manifest.ts'), ts);
  return manifest;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const manifest = compileAll();
    console.log(`compiled ${Object.keys(manifest).length} sprite(s)`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
