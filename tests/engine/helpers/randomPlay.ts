/**
 * Shared harness for property-style engine tests: generate random VALID actions from a seeded
 * RNG and play a game month by month. Every generated action is expected to be accepted.
 */
import { archetypeConfig } from '@/config/archetypes';
import { BOUNDS } from '@/config/defaults';
import { advanceMonth, applyAction, createGame, hasCar, round2 } from '@/engine';
import { makeRng, type Rng } from '@/engine/rng';
import type { AdvanceOptions } from '@/engine';
import type { ArchetypeId, EventEffect, GameAction, GameConfig, GameEvent, GameState, HousingKind, InsuranceLine } from '@/types/domain';

export const ARCHETYPE_IDS: ArchetypeId[] = ['college_student', 'entry_worker', 'professional', 'young_family'];
const HOUSING: HousingKind[] = ['rent', 'dorm', 'family', 'own'];
const LINES: InsuranceLine[] = ['health', 'auto', 'renters'];

const pick = <T>(rng: Rng, xs: readonly T[]): T => xs[rng.int(0, xs.length - 1)]!;
const money = (rng: Rng, max: number) => round2(rng.next() * max);

export function randomAllocation(rng: Rng) {
  const raw = [rng.next(), rng.next(), rng.next()].map((x) => Math.round(x * 1000) / 1000);
  const sum = raw.reduce((a, b) => a + b, 0) || 1;
  const stock = Math.round((raw[0]! / sum) * 1000) / 1000;
  const bond = Math.round((raw[1]! / sum) * 1000) / 1000;
  return { stock, bond, etf: Math.round((1 - stock - bond) * 1000) / 1000 };
}

export function randomEffect(rng: Rng, s: GameState): EventEffect {
  switch (rng.int(0, 6)) {
    case 0: return { template: 'none' };
    case 1: return { template: 'offer_job', grossAnnualSalary: money(rng, 150_000), title: 'Random role' };
    case 2: return { template: 'change_housing', housingMonthly: money(rng, 3000), housingKind: pick(rng, HOUSING) };
    case 3: {
      const line = pick(rng, LINES);
      const plans = s.assumptions.insurancePlans.filter((p) => p.line === line);
      // Auto cover needs a car; a car-less life can only hold "none".
      return { template: 'change_insurance', line, planId: rng.next() < 0.3 || (line === 'auto' && !hasCar(s)) ? null : pick(rng, plans).id };
    }
    case 4: return { template: 'budget_choice', discretionaryMonthly: money(rng, 1500) };
    case 5: return { template: 'loan_choice', principal: round2(1 + rng.next() * 20_000), apr: round2(rng.next() * 0.3), termMonths: rng.int(BOUNDS.loanTermMonthsMin, BOUNDS.loanTermMonthsMax), name: 'Random loan' };
    default: return { template: 'contribution_choice', savingsContributionPerMonth: money(rng, 1500), investmentContributionPerMonth: money(rng, 1500) };
  }
}

export function randomOpportunity(rng: Rng, s: GameState, n: number): GameEvent {
  const count = rng.int(1, 3);
  const options = Array.from({ length: count }, (_, i) => ({ id: `o${i}`, label: `Option ${i}`, description: '', effect: randomEffect(rng, s) }));
  return { id: `EVB_rand_${s.monthIndex}_${n}`, type: 'B', title: 'Random opportunity', body: 'Generated by the test harness', buildingTarget: 'bank', options, createdAtMonth: s.monthIndex, expiresAtMonth: s.monthIndex + rng.int(0, 3), source: 'fallback' };
}

/** One random action that must be valid for `s`, or null when nothing applies. */
export function randomAction(rng: Rng, s: GameState, n: number): GameAction | null {
  switch (rng.int(0, 11)) {
    case 0: return { type: 'set_contributions', savingsContributionPerMonth: money(rng, 2000), investmentContributionPerMonth: money(rng, 2000) };
    case 1: return { type: 'set_budget', discretionaryMonthly: money(rng, 1500) };
    case 2: return { type: 'set_allocation', allocation: randomAllocation(rng) };
    case 3: {
      const line = pick(rng, LINES);
      const plans = s.assumptions.insurancePlans.filter((p) => p.line === line);
      return { type: 'set_insurance', line, planId: rng.next() < 0.3 || (line === 'auto' && !hasCar(s)) ? null : pick(rng, plans).id };
    }
    case 4: return { type: 'set_extra_debt_payment', amount: money(rng, 500) };
    case 5: return { type: 'set_min_cash_buffer', amount: money(rng, 3000) };
    case 6: {
      const debts = s.debts.filter((d) => d.balance > 0);
      if (!debts.length || s.cash < 0.01) return null;
      const d = pick(rng, debts);
      const amount = round2(Math.max(0.01, Math.min(d.balance, s.cash) * rng.next()));
      return { type: 'make_extra_payment', debtId: d.id, amount };
    }
    case 7: {
      const from = rng.next() < 0.5 ? 'cash' : 'savings';
      const available = from === 'cash' ? s.cash : s.savings;
      if (available < 0.01) return null;
      return { type: 'transfer', from, to: from === 'cash' ? 'savings' : 'cash', amount: round2(Math.max(0.01, available * rng.next())) };
    }
    case 8: return { type: 'enqueue_event', event: randomOpportunity(rng, s, n) };
    case 9: return { type: 'set_housing', housingMonthly: money(rng, 3000), housingKind: pick(rng, HOUSING) };
    case 10: {
      // Car: any band, or none unless an auto loan is still outstanding (the engine refuses to sell a financed car).
      const financed = s.debts.some((d) => d.kind === 'auto_loan' && d.balance > 0);
      const band = pick(rng, financed ? (['cheap', 'mid', 'nice'] as const) : (['none', 'cheap', 'mid', 'nice'] as const));
      return { type: 'set_car', owned: band !== 'none', valueBand: band };
    }
    default: return null;
  }
}

export type Step = { monthIndex: number; action: GameAction };

export interface PlayOptions {
  seed: number;
  months?: number;
  actionSeed?: number;
  advance?: AdvanceOptions;
  /** Called with the state after every advanceMonth. */
  onMonth?: (prev: GameState, next: GameState) => void;
  /** Called after each accepted applyAction with the state before and after. */
  onAction?: (before: GameState, action: GameAction, after: GameState) => void;
  /** Assert applyAction / advanceMonth never mutate their input (JSON snapshot compare). */
  checkPurity?: boolean;
}

/** Play `months` with random valid actions; returns the final state and every applied step. */
export function playRandom(archetype: ArchetypeId, opts: PlayOptions): { config: GameConfig; state: GameState; steps: Step[] } {
  const months = opts.months ?? 24;
  const config = archetypeConfig(archetype, opts.seed, { durationMonths: months });
  const rng = makeRng(opts.actionSeed ?? opts.seed * 7919 + 13);
  let s = createGame(config);
  const steps: Step[] = [];
  const apply = (action: GameAction) => {
    const before = s;
    const snapshot = opts.checkPurity ? JSON.stringify(before) : '';
    const r = applyAction(before, action);
    if (!r.ok) throw new Error(`Generated action rejected (${r.code}: ${r.message}) ${JSON.stringify(action)}`);
    if (opts.checkPurity && JSON.stringify(before) !== snapshot) throw new Error(`applyAction mutated its input: ${JSON.stringify(action)}`);
    s = r.state;
    steps.push({ monthIndex: s.monthIndex, action });
    opts.onAction?.(before, action, s);
  };
  for (let m = 0; m < months; m++) {
    const count = rng.int(0, 3);
    for (let i = 0; i < count; i++) {
      const a = randomAction(rng, s, i);
      if (a) apply(a);
    }
    for (const ev of [...s.activeEvents]) {
      if (rng.next() < 0.2) apply({ type: 'dismiss_event', eventId: ev.id });
      else apply({ type: 'apply_event_option', eventId: ev.id, optionId: pick(rng, ev.options).id });
    }
    const prev = s;
    const snapshot = opts.checkPurity && !opts.advance?.inPlace ? JSON.stringify(prev) : '';
    s = advanceMonth(prev, opts.advance);
    if (snapshot && JSON.stringify(prev) !== snapshot) throw new Error(`advanceMonth mutated its input at month ${prev.monthIndex}`);
    opts.onMonth?.(prev, s);
  }
  return { config, state: s, steps };
}

/** Replay recorded steps on a fresh game (optionally lean) and return the final state. */
export function replaySteps(config: GameConfig, steps: Step[], advance: AdvanceOptions = {}): GameState {
  let s = createGame(config);
  let i = 0;
  for (let m = 0; m < config.durationMonths; m++) {
    for (; i < steps.length && steps[i]!.monthIndex === m; i++) {
      const r = applyAction(s, steps[i]!.action);
      if (!r.ok) throw new Error(`Replay rejected step ${i}: ${r.message}`);
      s = r.state;
    }
    s = advanceMonth(s, advance);
  }
  return s;
}

/** Recursively assert every number in `value` is finite. Returns the first offending path or null. */
export function firstNonFinite(value: unknown, path = 'state'): string | null {
  if (typeof value === 'number') return Number.isFinite(value) ? null : path;
  if (Array.isArray(value)) {
    for (let i = 0; i < value.length; i++) { const p = firstNonFinite(value[i], `${path}[${i}]`); if (p) return p; }
    return null;
  }
  if (value && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) { const p = firstNonFinite(v, `${path}.${k}`); if (p) return p; }
  }
  return null;
}
