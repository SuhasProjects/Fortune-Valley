import { test, expect } from '@playwright/test'

test('larger text fits a narrow phone without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.life-card p').first()).toHaveCSS('font-size', '22px')
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 320)
  await page.getByRole('button', { name: /College Student/ }).click()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 320)
  await page.getByRole('button', { name: /Open Pine Bank/ }).click()
  await expect(page.getByRole('dialog', { name: 'Pine Bank' })).toBeVisible()
})

test('town navigation, focus, month tick, history and finish', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/api/ai', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":"disabled"}' }))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your money. Your little world.' })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('heading', { name: 'Your money. Your little world.' })).toHaveCSS('font-family', /Pixelify Sans/)
  await expect(page.locator('.world-backdrop')).toHaveCSS('position', 'fixed')
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
  await page.screenshot({ path: `test-results/screenshots/${testInfo.project.name}-landing.png`, fullPage: true })
  await page.getByRole('button', { name: /Entry-Level Worker/ }).click()
  await expect(page.getByRole('timer')).toContainText('Next month in 60s')
  const image = page.locator('.town-illustration')
  const geometry = await image.evaluate(element => ({ width: element.getBoundingClientRect().width, height: element.getBoundingClientRect().height, source: (element as HTMLImageElement).getAttribute('src') }))
  expect(geometry.source).toBe('/assets/town-valley-v3.png')
  expect(geometry.width / geometry.height).toBeCloseTo(1.5, 2)
  expect(geometry.height).toBeLessThanOrEqual(await page.evaluate(() => innerHeight))
  for (const name of ['Pine Bank', 'Town Office', 'Health House', 'Your Home', 'Market Hall']) {
    const button = page.getByRole('button', { name: new RegExp(`Open ${name}:`) })
    await button.scrollIntoViewIfNeeded()
    await button.click()
    await expect(page.getByRole('dialog', { name })).toBeVisible()
    await page.keyboard.press('Escape')
    await button.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name })
    await expect(dialog).toBeVisible()
    // Native dialogs trap Tab inside the panel.
    await page.keyboard.press('Tab')
    await expect(dialog).toContainText('At a glance')
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(button).toBeFocused()
  }
  await page.getByRole('button', { name: /Next month/ }).click()
  await expect(page.getByText(/^Month 1 \/ \d+$/)).toBeVisible()
  await page.getByRole('button', { name: /Pause/ }).click()
  await expect(page.getByRole('button', { name: /Next month/ })).toBeDisabled()
  await page.getByRole('button', { name: /Resume/ }).click()
  await page.getByRole('button', { name: /Next month/ }).click()
  await page.getByRole('button', { name: /Next month/ }).click()
  await expect(page.getByRole('button', { name: /Decision waiting/ }).first()).toBeVisible()
  await page.getByRole('button', { name: 'View all activity' }).click()
  await expect(page.getByRole('dialog', { name: 'Town activity' })).toBeVisible()
  await page.getByRole('button', { name: 'Close panel' }).click()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
  await page.getByRole('button', { name: /Recent activity/ }).click()
  await expect(page.locator('.activity-area .notice')).toHaveCount(3)
  await page.screenshot({ path: `test-results/screenshots/${testInfo.project.name}-activity.png`, fullPage: true })
  await page.getByRole('button', { name: 'Hide recent activity' }).click()
  await page.screenshot({ path: `test-results/screenshots/${testInfo.project.name}-town.png`, fullPage: true })
  await page.getByRole('button', { name: /Open Pine Bank/ }).click()
  await page.screenshot({ path: `test-results/screenshots/${testInfo.project.name}-panel.png`, fullPage: true })
  // The narrow mobile dialog leaves only 8px of backdrop outside its bounds.
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: /Finish & reveal/ }).click()
  await expect(page.getByRole('dialog', { name: 'Your next chapter' })).toContainText('Same strategy, 1,000 futures')
  await page.screenshot({ path: `test-results/screenshots/${testInfo.project.name}-results.png`, fullPage: true })
  await page.getByRole('button', { name: /Choose a new story/ }).click()
  await expect(page.getByRole('heading', { name: 'Your money. Your little world.' })).toBeVisible()
  await expect(page.locator('body')).not.toHaveClass(/fullscreen-game-active/)
  expect(await page.evaluate(() => getComputedStyle(document.body).overflow)).not.toBe('hidden')
  expect(errors).toEqual([])
})

test('automatically advances a month at 60 seconds and manual advance resets the countdown', async ({ page }) => {
  await page.clock.install()
  await page.route('**/api/ai', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":"disabled"}' }))
  await page.goto('/')
  await page.getByRole('button', { name: /Entry-Level Worker/ }).click()
  await expect(page.getByRole('timer')).toContainText('Next month in 60s')
  await page.clock.fastForward(59_000)
  await expect(page.getByText(/^Month 0 \/ \d+$/)).toBeVisible()
  await page.clock.fastForward(1000)
  await expect(page.getByText(/^Month 1 \/ \d+$/)).toBeVisible()
  await page.getByRole('button', { name: /Next month/ }).click()
  await expect(page.getByRole('timer')).toContainText('Next month in 60s')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.clock.fastForward(120_000)
  await expect(page.getByText(/^Month 2 \/ \d+$/)).toBeVisible()
})
