import { test, expect } from '@playwright/test'

test('larger text fits a narrow phone without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.welcome-life-card p').first()).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 320)
  await page.getByRole('button', { name: /College Student/ }).click()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 320)
  await page.getByRole('button', { name: /Open Pine Bank/ }).click()
  await expect(page.getByRole('dialog', { name: 'Pine Bank' })).toBeVisible()
})

test('town navigation, focus, month tick, history and finish', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/api/ai', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":"disabled"}' }))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Small choices. A clearer financial future.' })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('heading', { name: 'Small choices. A clearer financial future.' })).toHaveCSS('font-family', /sans-serif/)
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
  await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-landing.png`, fullPage: true })
  await page.getByRole('button', { name: /Entry-Level Worker/ }).click()
  for (const name of ['Pine Bank', 'Town Office', 'Health House', 'Your Home', 'Market Hall']) {
    const button = page.getByRole('button', { name: new RegExp(`Open ${name}:`) })
    await button.scrollIntoViewIfNeeded()
    await button.click()
    await expect(page.getByRole('dialog', { name })).toBeVisible()
    await page.keyboard.press('Escape')
    await button.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name })
    await expect(dialog).toBeVisible()
    // Native dialogs trap Tab inside the panel.
    await page.keyboard.press('Tab')
    await expect(dialog).toContainText('Your decision')
    if (name === 'Market Hall') {
      await expect(dialog.getByRole('group', { name: 'Stocks allocation' })).toContainText('Last month')
      await expect(dialog.getByRole('group', { name: 'Stocks allocation' })).toContainText('Annual assumption')
      await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-market.png` })
    }
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(button).toBeFocused()
  }
  await page.getByRole('button', { name: /Next month/ }).click()
  await expect(page.getByText(/^Month 1 \/ \d+$/)).toBeVisible()
  await page.getByRole('button', { name: /Pause/ }).click()
  await expect(page.getByRole('button', { name: /Next month/ })).toBeDisabled()
  await page.getByRole('button', { name: /Resume/ }).click()
  await page.getByRole('button', { name: /Next month/ }).click()
  await page.getByRole('button', { name: /Next month/ }).click()
  await expect(page.getByRole('button', { name: /Decision waiting/ }).first()).toBeVisible()
  await page.getByRole('button', { name: 'View all activity' }).click()
  await expect(page.getByRole('dialog', { name: 'Town activity' })).toBeVisible()
  await page.getByRole('button', { name: 'Close panel' }).click()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
  await expect(page.locator('.activity-area .notice')).toHaveCount(3)
  await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-town.png`, fullPage: true })
  await page.getByRole('button', { name: /Open Pine Bank/ }).click()
  await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-panel.png`, fullPage: true })
  // The narrow mobile dialog leaves only 8px of backdrop outside its bounds.
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: /Finish & reveal/ }).click()
  await expect(page.getByRole('dialog', { name: 'Your next chapter' })).toContainText('Same strategy, 1,000 futures')
  await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-results.png`, fullPage: true })
  await page.getByRole('button', { name: /Choose a new story/ }).click()
  await expect(page.getByRole('heading', { name: 'Small choices. A clearer financial future.' })).toBeVisible()
  expect(errors).toEqual([])
})

test('financial policies save through the town and persist after a month', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Entry-Level Worker/ }).click()
  await page.getByRole('button', { name: /Open Pine Bank:/ }).click()
  await page.getByLabel('Monthly savings contribution (USD)', { exact: true }).fill('300')
  await expect(page.getByLabel('12-month policy preview')).toContainText('After 12 months')
  await page.getByRole('button', { name: 'Save savings contribution', exact: true }).click()
  await expect(page.getByText('Saved.')).toBeVisible()
  await page.getByRole('button', { name: 'Close panel' }).click()
  await page.getByRole('button', { name: /Next month/ }).click()
  await page.getByRole('button', { name: /Open Pine Bank:/ }).click()
  await expect(page.getByLabel('Monthly savings contribution (USD)', { exact: true })).toHaveValue('300')
})

test('landing navigation expands instructions and keeps account placeholders inactive', async ({ page }) => {
  await page.goto('/')
  const how = page.getByRole('button', { name: 'How it works', exact: true })
  await expect(how).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: 'Choose a starting point' })).not.toBeVisible()
  await how.click()
  await expect(how).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('heading', { name: 'Choose a starting point' })).toBeVisible()
  await how.click()
  await expect(how).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: 'Choose a starting point' })).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Create account', exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'Starting lives', exact: true }).click()
  await expect(page).toHaveURL(/#starting-lives$/)
  await expect(page.getByRole('button', { name: /College Student/ })).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
})

test('sticky landing menu reaches the game guide and accessible FAQs', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Learn by living a little.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Play a month. See what changes.' })).toBeVisible()
  await page.getByRole('link', { name: 'The town', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Five buildings. Connected choices.' })).toBeVisible()
  await expect(page.locator('.welcome-header')).toHaveCSS('position', 'sticky')
  await expect.poll(() => page.locator('.welcome-header').evaluate(el => el.getBoundingClientRect().top)).toBe(0)
  await page.getByRole('link', { name: 'FAQs', exact: true }).click()
  await page.getByText('Is any real money involved?', { exact: true }).click()
  await expect(page.getByText('No. Every balance, paycheck, investment, and payment belongs to a fictional simulation. No bank connection is needed.')).toBeVisible()
  await expect.poll(() => page.locator('.welcome-header').evaluate(el => el.getBoundingClientRect().top)).toBe(0)
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.evaluate(() => innerWidth))
  expect(await page.locator('.welcome-page').innerText()).not.toMatch(/[↗↓↑↳⌄]/)
  await page.getByRole('button', { name: 'How it works', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Choose a starting point' })).toBeVisible()
})
